def load_json(name: str, default: Any) -> Any:
    try:
        return json.loads((ROOT / name).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default

def value_text(value: Any, fallback: str = "—") -> str:
    text = str(value or "").strip()
    return text or fallback

def esc(value: Any, fallback: str = "—") -> str:
    return html.escape(value_text(value, fallback), quote=True)

def parse_dt(value: Any):
    raw = str(value or "").strip()
    if not raw:
        return None
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(timezone.utc)
    except ValueError:
        return None

def human_date(value: Any, lang: str) -> str:
    dt = parse_dt(value)
    if not dt:
        return "—"
    return dt.strftime("%d/%m/%Y · %H:%M UTC" if lang == "es" else "%Y-%m-%d · %H:%M UTC")

def lang_for(filename: str, document: str = "") -> str:
    language = re.search(r'<html\b[^>]*\blang=["\']([^"\']+)', document, re.I)
    if language:
        return "en" if language.group(1).lower().startswith("en") else "es"
    return "en" if filename == "en.html" or filename.startswith("en-") else "es"

def _replace_inner_html(document: str, opening_pattern: re.Pattern[str], content: str) -> str:
    """Replace inner HTML while respecting nested elements of the same tag."""
    match = opening_pattern.search(document)
    if not match:
        return document
    tag = match.group("tag")
    start_inner = match.end()
    token_re = re.compile(
        rf"<{re.escape(tag)}\b[^>]*>|</{re.escape(tag)}\s*>",
        re.I | re.S,
    )
    depth = 1
    for token in token_re.finditer(document, start_inner):
        raw = token.group(0)
        if raw.lower().startswith(f"</{tag.lower()}"):
            depth -= 1
            if depth == 0:
                return document[:start_inner] + content + document[token.start():]
        elif not raw.rstrip().endswith("/>"):
            depth += 1
    raise RuntimeError(f"No matching closing tag for <{tag}>")

def replace_element(document: str, element_id: str, content: str) -> str:
    opening = re.compile(
        rf'<(?P<tag>[A-Za-z0-9]+)\b[^>]*\bid=["\']{re.escape(element_id)}["\'][^>]*>',
        re.I | re.S,
    )
    return _replace_inner_html(document, opening, content)

def replace_data_attr_content(document: str, attr: str, content: str) -> str:
    opening = re.compile(
        rf'<(?P<tag>[A-Za-z0-9]+)\b[^>]*\b{re.escape(attr)}(?:=["\'][^"\']*["\'])?[^>]*>',
        re.I | re.S,
    )
    return _replace_inner_html(document, opening, content)


def set_element_attrs(document: str, element_id: str, **attrs: str) -> str:
    pattern = re.compile(rf'<[A-Za-z0-9]+\b[^>]*\bid=["\']{re.escape(element_id)}["\'][^>]*>', re.I)
    def patch(match):
        tag = match.group(0)
        for key, value in attrs.items():
            key = key.replace("_", "-")
            tag = re.sub(rf'\s+{re.escape(key)}(?:=["\'][^"\']*["\'])?(?=\s|>)', "", tag, flags=re.I)
            tag = tag[:-1] + f' {key}="{html.escape(str(value), quote=True)}">'
        return tag
    return pattern.sub(patch, document, count=1)


def archive_items(status: dict[str, Any]) -> list[dict[str, Any]]:
    items, seen = [], set()
    for item in (status.get("evidence_archive") or []) + (status.get("evidence") or []):
        if not isinstance(item, dict) or not item.get("title"):
            continue
        key = tuple(str(item.get(k) or "").strip().casefold() for k in ("source_name", "title", "source_url"))
        if key in seen:
            continue
        seen.add(key)
        items.append(item)
    return sorted(items, key=lambda x: str(x.get("published_at") or x.get("observed_at") or ""), reverse=True)


def render_archive(document: str, status: dict[str, Any], lang: str) -> str:
    if 'id="archiveList"' not in document:
        return document
    items = archive_items(status)
    sources = sorted({str(x.get("source_name") or "—") for x in items}, key=str.casefold)
    cards = []
    for item in items:
        source = str(item.get("source_name") or "—")
        url = str(item.get("source_url") or "")
        title = esc(item.get("title"))
        link = f'<a href="{esc(url)}" target="_blank" rel="noopener noreferrer nofollow">{title}</a>' if url.startswith(("https://", "http://")) else title
        cards.append(
            f'<article class="archive-item" data-archive-item data-source="{esc(source)}">'
            f'<div class="archive-date"><span>{"Publicada" if lang == "es" else "Published"}</span>'
            f'<strong>{esc(human_date(item.get("published_at") or item.get("observed_at"), lang))}</strong></div>'
            f'<div class="archive-item-main"><div class="archive-badges"><span class="archive-badge">{esc(item.get("signal"))}</span></div>'
            f'<h2>{link}</h2><p class="archive-item-source">{esc(source)}</p></div></article>'
        )
    empty = "No hay evidencias que coincidan con estos filtros." if lang == "es" else "No evidence matches these filters."
    document = replace_element(document, "archiveList", "".join(cards) + f'<p class="archive-empty" data-archive-empty{ " hidden" if items else ""}>{empty}</p>')
    document = set_element_attrs(document, "archiveList", **{"class": "archive-list"})
    options = '<option value="all">' + ("Todas las fuentes" if lang == "es" else "All sources") + '</option>'
    options += "".join(f'<option value="{esc(source)}">{esc(source)}</option>' for source in sources)
    document = replace_element(document, "archiveSource", options)
    for key, value in {
        "archiveMetricChecked": human_date(status.get("checked_at"), lang),
        "archiveMetricDays": str((status.get("diagnostics") or {}).get("evidence_archive_days", 14)) + (" días" if lang == "es" else " days"),
        "archiveMetricCount": len(items), "archiveMetricSources": len(sources),
        "archiveSummary": f'{len(items)} ' + ("resultados" if lang == "es" else "results"),
    }.items():
        document = replace_element(document, key, html.escape(str(value)))
    return document

def set_status_hero_class(document: str, family: str) -> str:
    state_class = {
        "OPEN": "is-open",
        "CLOSED": "is-closed",
    }.get(str(family or "").upper(), "is-uncertain")

    tag_re = re.compile(
        r'<(?P<tag>[A-Za-z0-9]+)\b(?=[^>]*\bid=["\']statusHero["\'])[^>]*>',
        re.I | re.S,
    )
    match = tag_re.search(document)
    if not match:
        return document

    opening = match.group(0)
    class_re = re.compile(r'\bclass=["\']([^"\']*)["\']', re.I)
    class_match = class_re.search(opening)
    classes = class_match.group(1).split() if class_match else []
    classes = [c for c in classes if c not in {"is-loading", "is-open", "is-closed", "is-uncertain", "is-provisional"}]
    classes.append(state_class)
    class_value = " ".join(dict.fromkeys(classes))

    if class_match:
        patched_opening = opening[:class_match.start()] + f'class="{class_value}"' + opening[class_match.end():]
    else:
        patched_opening = opening[:-1] + f' class="{class_value}">'
    return document[:match.start()] + patched_opening + document[match.end():]

def public_assessment(status: dict[str, Any]) -> dict[str, Any]:
    op = status.get("operational_intelligence")
    if isinstance(op, dict) and op.get("state"):
        return op
    separate = load_json("operational-intelligence.json", {})
    if isinstance(separate, dict) and separate.get("state"):
        return separate
    return {
        "family": (
            "OPEN" if status.get("status") == "ABIERTO"
            else "CLOSED" if status.get("status") == "CERRADO"
            else "UNKNOWN"
        ),
        "label_es": status.get("operational_label_es") or status.get("status") or "INCIERTO",
        "label_en": status.get("operational_label_en") or status.get("status") or "UNCERTAIN",
        "operational_label_es": status.get("operational_label_es") or "",
        "operational_label_en": status.get("operational_label_en") or "",
        "summary_es": status.get("summary_es") or "",
        "summary_en": status.get("summary_en") or "",
        "confidence": status.get("confidence") or "BAJA",
        "generated_at": status.get("checked_at"),
        "latest_confirmed_transit_at": (status.get("last_valid_confirmation") or {}).get("at"),
    }

def render_evidence(status: dict[str, Any], lang: str, limit: int) -> str:
    items = status.get("evidence")
    if not isinstance(items, list):
        items = []
    cards = []
    for item in items[:limit]:
        if not isinstance(item, dict):
            continue
        cards.append(
            '<article class="evidence-card">'
            f'<div class="evidence-meta"><span>{esc(item.get("signal"), "Evidencia" if lang=="es" else "Evidence")}</span>'
            f'<time>{esc(human_date(item.get("published_at"), lang))}</time></div>'
            f'<h3><a href="{esc(item.get("source_url"), "#")}" target="_blank" rel="noopener noreferrer">'
            f'{esc(item.get("title"), "Evidencia" if lang=="es" else "Evidence")}</a></h3>'
            f'<p>{esc(item.get("source_name"), "Fuente" if lang=="es" else "Source")}</p>'
            '</article>'
        )
    return "".join(cards) or (
        '<p class="empty-state">No hay evidencias recientes publicables.</p>'
        if lang == "es" else
        '<p class="empty-state">No recent publishable evidence.</p>'
    )

def render_history(history: Any, lang: str, limit: int) -> str:
    if not isinstance(history, list):
        history = []
    rows = []
    for item in history[:limit]:
        if not isinstance(item, dict):
            continue
        label = (
            item.get("operational_label_es" if lang == "es" else "operational_label_en")
            or item.get("status")
        )
        summary = item.get("summary_es" if lang == "es" else "summary_en") or ""
        raw_status = str(item.get("status") or "").upper()
        timeline_class = (
            "is-open" if raw_status == "ABIERTO"
            else "is-closed" if raw_status == "CERRADO"
            else "is-uncertain"
        )
        rows.append(
            f'<article class="timeline-item {timeline_class}"><div class="timeline-marker" aria-hidden="true"></div><div class="timeline-content">'
            f'<div class="timeline-head"><strong>{esc(label)}</strong>'
            f'<time>{esc(human_date(item.get("at"), lang))}</time></div>'
            f'<p>{esc(summary, "")}</p></div></article>'
        )
    return "".join(rows) or (
        '<p class="empty-state">Sin cambios significativos archivados.</p>'
        if lang == "es" else
        '<p class="empty-state">No material changes archived.</p>'
    )

def prerender(document: str, filename: str) -> str:
    lang = lang_for(filename, document)
    status = load_json("status.json", {})
    history = load_json("history.json", [])
    brief = load_json("daily-brief.json", {})
    if not isinstance(status, dict):
        status = {}
    assessment = public_assessment(status)
    document = set_status_hero_class(document, assessment.get("family"))

    label = assessment.get("label_es" if lang == "es" else "label_en")
    operational = assessment.get("operational_label_es" if lang == "es" else "operational_label_en")
    summary = assessment.get("summary_es" if lang == "es" else "summary_en")
    confidence = value_text(assessment.get("confidence"), "BAJA")
    confidence_label = (
        {"ALTA": "Alta", "MEDIA": "Media", "BAJA": "Baja"}.get(confidence, confidence)
        if lang == "es"
        else {"ALTA": "High", "MEDIA": "Medium", "BAJA": "Low"}.get(confidence, confidence)
    )
    generated = assessment.get("generated_at") or status.get("checked_at")
    latest = assessment.get("latest_confirmed_transit_at")

    for element_id, value in (
        ("statusWord", esc(label)),
        ("operationalLabel", esc(operational, "")),
        ("statusSummary", esc(summary, "")),
        ("checkedAt", esc(human_date(generated, lang))),
        ("confidence", esc(confidence_label)),
        ("lastValidAt", esc(human_date(latest, lang))),
    ):
        document = replace_element(document, element_id, value)

    document = replace_element(document, "evidenceList", render_evidence(status, lang, 8))
    document = replace_element(document, "evidenceArchive", render_evidence(status, lang, 20))
    document = replace_element(document, "recentHistory", render_history(history, lang, 3))
    document = replace_element(document, "historyTimeline", render_history(history, lang, 50))
    document = render_archive(document, status, lang)

    diagnostics = status.get("diagnostics") or {}
    counts = (diagnostics.get("independent_sources") or {}).values()
    verified = status.get("verification_ok") is True
    stale = bool(status.get("stale"))
    system = (("Comprobación incompleta" if lang == "es" else "Incomplete verification") if not verified else
              ("Datos pendientes de actualización" if lang == "es" else "Data awaiting update") if stale else
              ("Seguimiento activo" if lang == "es" else "Monitoring active"))
    for key, value in {
        "verificationProviders": len(diagnostics.get("providers_ok") or []),
        "verificationSources": max((int(x) for x in counts if isinstance(x, (int, float))), default=0),
        "verificationSignals": diagnostics.get("signals_considered", "—"),
        "verificationFreshness": human_date(status.get("checked_at"), lang),
        "systemStatus": system,
    }.items():
        document = replace_element(document, key, html.escape(str(value)))
    document = set_element_attrs(document, "systemStatus", **{"class": "system-status " + ("is-error" if not verified else "is-warning" if stale else "is-operational")})
    document = set_element_attrs(document, "verificationFreshness", data_checked_at=str(status.get("checked_at") or ""))

    if isinstance(history, list):
        document = replace_element(document, "historyEventCount", str(len(history)))
        document = replace_element(document, "historyCount", str(len(history)))
        if history:
            document = replace_element(document, "historyLastChange", esc(human_date(history[0].get("at"), lang)))
    document = replace_element(document, "historyCurrentStatus", esc(label))

    if isinstance(brief, dict):
        suffix = "es" if lang == "es" else "en"
        for element_id, value in {
            "briefDate": brief.get("date") or brief.get("generated_at"),
            "briefStatusPill": brief.get(f"status_label_{suffix}") or label,
            "briefOperational": brief.get(f"operational_label_{suffix}") or operational,
            "briefSummary": brief.get(f"summary_{suffix}") or summary,
            "briefGenerated": human_date(brief.get("generated_at"), lang),
            "briefChange": brief.get(f"change_{suffix}") or "",
            "briefConfidence": (brief.get("confidence_label") or {}).get(lang) or brief.get("confidence") or "—",
        }.items():
            document = replace_element(document, element_id, esc(value, ""))
        document = replace_element(
            document, "briefRisks",
            "".join(f"<li>{esc(item)}</li>" for item in (brief.get(f"risks_{suffix}") or [])),
        )
        document = replace_element(document, "briefEvidence", render_evidence({"evidence": brief.get("evidence") or []}, lang, 5))
        document = replace_element(
            document, "briefWatch",
            "".join(f"<li>{esc(item)}</li>" for item in (brief.get(f"watchlist_{suffix}") or [])),
        )
        archive = load_json("daily-brief-archive.json", [])
        if isinstance(archive, dict):
            archive = archive.get("items") or []
        document = replace_element(document, "briefArchive", "".join(
            f'<article><time>{esc(item.get("date"))}</time><h3>{esc(item.get(f"operational_label_{suffix}"))}</h3><p>{esc(item.get(f"summary_{suffix}"))}</p></article>'
            for item in archive[:6] if isinstance(item, dict)
        ))
        if brief:
            document = set_element_attrs(document, "briefLoading", hidden="hidden")

    if filename in {"widget.html", "en-widget.html"}:
        document = replace_data_attr_content(document, "data-state", esc(label))
        document = replace_data_attr_content(document, "data-summary", esc(summary, ""))
        document = replace_data_attr_content(document, "data-confidence", esc(confidence_label))
        document = replace_data_attr_content(document, "data-updated", esc(human_date(generated, lang)))
        document = re.sub(
            r'<script\b[^>]*src=["\']/?widget\.js(?:\?[^"\']*)?["\'][^>]*>\s*</script>',
            '<script defer src="/public-widget.min.js"></script>',
            document, flags=re.I | re.S,
        )
    return document

def strip_private_scripts(document: str) -> str:
    document = re.sub(
        r'<script\b[^>]*src=["\']/?(?:app|daily-brief|evidence-ui|evidence-archive|'
        r'operational-v7|social-studio|widget)\.js(?:\?[^"\']*)?["\'][^>]*>\s*</script>',
        "", document, flags=re.I | re.S,
    )
    document = re.sub(
        r'<script\b(?![^>]*type=["\']application/ld\+json["\'])[^>]*>'
        r'(?:(?!</script>).)*?(?:status|history|config|sources|daily-brief|'
        r'operational-intelligence|journal-state|journal-health)\.json'
        r'(?:(?!</script>).)*?</script>',
        "", document, flags=re.I | re.S,
    )
    return document

