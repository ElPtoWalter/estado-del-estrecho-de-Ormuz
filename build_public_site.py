def load_json(name: str, default: Any) -> Any:
    path = ROOT / name
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default

def text(value: Any, fallback: str = "—") -> str:
    out = str(value or "").strip()
    return out or fallback

def esc(value: Any, fallback: str = "—") -> str:
    return html.escape(text(value, fallback), quote=True)

def parse_dt(value: Any):
    raw = str(value or "").strip()
    if not raw:
        return None
    try:
        dt = datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(timezone.utc)
    except ValueError:
        return None

def human_date(value: Any, lang: str) -> str:
    dt = parse_dt(value)
    if not dt:
        return "—"
    return dt.strftime("%d/%m/%Y · %H:%M UTC" if lang == "es" else "%Y-%m-%d · %H:%M UTC")

def replace_element(document: str, element_id: str, content: str) -> str:
    pattern = re.compile(
        rf'(<(?P<tag>[A-Za-z0-9]+)\b[^>]*\bid=["\']{re.escape(element_id)}["\'][^>]*>)'
        rf'.*?(</(?P=tag)>)',
        re.I | re.S,
    )
    return pattern.sub(lambda m: m.group(1) + content + m.group(3), document, count=1)

def public_assessment(status: dict[str, Any]) -> dict[str, Any]:
    op = status.get("operational_intelligence")
    if isinstance(op, dict) and op.get("state"):
        return op
    separate = load_json("operational-intelligence.json", {})
    if isinstance(separate, dict) and separate.get("state"):
        return separate
    return {
        "label_es": status.get("operational_label_es") or status.get("status") or "INCIERTO",
        "label_en": status.get("operational_label_en") or status.get("status") or "UNCERTAIN",
        "operational_label_es": status.get("operational_label_es") or "",
        "operational_label_en": status.get("operational_label_en") or "",
        "summary_es": status.get("summary_es") or "",
        "summary_en": status.get("summary_en") or "",
        "confidence": status.get("confidence") or "BAJA",
        "generated_at": status.get("checked_at"),
        "latest_confirmed_transit_at": (status.get("last_valid_confirmation") or {}).get("at"),
    }

def render_evidence(status: dict[str, Any], lang: str, limit: int) -> str:
    items = status.get("evidence")
    if not isinstance(items, list):
        items = []
    cards = []
    for item in items[:limit]:
        if not isinstance(item, dict):
            continue
        cards.append(
            '<article class="evidence-card">'
            f'<div class="evidence-meta"><span>{esc(item.get("signal"), "Evidencia" if lang=="es" else "Evidence")}</span>'
            f'<time>{esc(human_date(item.get("published_at"), lang))}</time></div>'
            f'<h3><a href="{esc(item.get("source_url"), "#")}" target="_blank" rel="noopener noreferrer">'
            f'{esc(item.get("title"), "Evidencia" if lang=="es" else "Evidence")}</a></h3>'
            f'<p>{esc(item.get("source_name"), "Fuente" if lang=="es" else "Source")}</p>'
            '</article>'
        )
    if cards:
        return "".join(cards)
    return (
        '<p class="empty-state">No hay evidencias recientes publicables.</p>'
        if lang == "es" else
        '<p class="empty-state">No recent publishable evidence.</p>'
    )

def render_history(history: Any, lang: str, limit: int) -> str:
    if not isinstance(history, list):
        history = []
    rows = []
    for item in history[:limit]:
        if not isinstance(item, dict):
            continue
        label = (
            item.get("operational_label_es" if lang == "es" else "operational_label_en")
            or item.get("status")
        )
        summary = item.get("summary_es" if lang == "es" else "summary_en") or ""
        rows.append(
            '<article class="timeline-item"><div class="timeline-content">'
            f'<div class="timeline-head"><strong>{esc(label)}</strong>'
            f'<time>{esc(human_date(item.get("at"), lang))}</time></div>'
            f'<p>{esc(summary, "")}</p></div></article>'
        )
    return "".join(rows) or (
        '<p class="empty-state">Sin cambios significativos archivados.</p>'
        if lang == "es" else
        '<p class="empty-state">No material changes archived.</p>'
    )

def prerender(document: str, filename: str) -> str:
    lang = "en" if filename.startswith("en-") or filename == "en.html" else "es"
    status = load_json("status.json", {})
    history = load_json("history.json", [])
    brief = load_json("daily-brief.json", {})
    if not isinstance(status, dict):
        status = {}
    assessment = public_assessment(status)

    label = assessment.get("label_es" if lang == "es" else "label_en")
    operational = assessment.get("operational_label_es" if lang == "es" else "operational_label_en")
    summary = assessment.get("summary_es" if lang == "es" else "summary_en")
    confidence = text(assessment.get("confidence"), "BAJA")
    confidence = (
        {"ALTA":"Alta","MEDIA":"Media","BAJA":"Baja"}.get(confidence, confidence)
        if lang == "es"
        else {"ALTA":"High","MEDIA":"Medium","BAJA":"Low"}.get(confidence, confidence)
    )

    for element_id, value in (
        ("statusWord", esc(label)),
        ("operationalLabel", esc(operational, "")),
        ("statusSummary", esc(summary, "")),
        ("checkedAt", esc(human_date(assessment.get("generated_at") or status.get("checked_at"), lang))),
        ("confidence", esc(confidence)),
        ("lastValidAt", esc(human_date(assessment.get("latest_confirmed_transit_at"), lang))),
    ):
        document = replace_element(document, element_id, value)

    document = replace_element(document, "evidenceList", render_evidence(status, lang, 8))
    document = replace_element(document, "evidenceArchive", render_evidence(status, lang, 20))
    document = replace_element(document, "recentHistory", render_history(history, lang, 3))
    document = replace_element(document, "historyTimeline", render_history(history, lang, 50))

    if isinstance(history, list):
        document = replace_element(document, "historyEventCount", str(len(history)))
        if history:
            document = replace_element(document, "historyLastChange", esc(human_date(history[0].get("at"), lang)))
    document = replace_element(document, "historyCurrentStatus", esc(label))

    if isinstance(brief, dict):
        suffix = "es" if lang == "es" else "en"
        values = {
            "briefDate": brief.get("date") or brief.get("generated_at"),
            "briefStatusPill": brief.get(f"status_label_{suffix}") or label,
            "briefOperational": brief.get(f"operational_label_{suffix}") or operational,
            "briefSummary": brief.get(f"summary_{suffix}") or summary,
            "briefGenerated": human_date(brief.get("generated_at"), lang),
            "briefChange": brief.get(f"change_{suffix}") or "",
        }
        for element_id, value in values.items():
            document = replace_element(document, element_id, esc(value, ""))

    return document

def sanitize_text(document: str) -> str:
    document = INTERNAL_LINK_RE.sub("", document)
    document = GITHUB_LINK_RE.sub("", document)
    document = BLOCKED_SCRIPT_RE.sub("", document)

    document = re.sub(
        r'<code>\s*(?:status|history|sources|daily-brief|operational-intelligence)\.json\s*</code>',
        "datos internos del observatorio",
        document,
        flags=re.I,
    )

    for old, new in REPLACEMENTS:
        document = document.replace(old, new)

    document = re.sub(
        r'\b(?:sistema|proceso)\s+automatizad[oa]\b',
        "sistema editorial de seguimiento",
        document,
        flags=re.I,
    )
    document = re.sub(
        r'\b(?:AI[- ]generated|generated\s+(?:by|with)\s+AI|written\s+(?:by|with)\s+AI|ChatGPT|OpenAI|LLM)\b',
        "Equipo editorial de Estrecho Ormuz",
        document,
        flags=re.I,
    )
    return document

def editorialize_jsonld(document: str) -> str:
    def patch(match):
        try:
            data = json.loads(match.group(2))
        except json.JSONDecodeError:
            return match.group(0)

        def walk(value):
            if isinstance(value, dict):
                if value.get("@type") in {"Article","NewsArticle","AnalysisNewsArticle","Report"}:
                    value["author"] = {
                        "@type": "Organization",
                        "name": "Equipo editorial de Estrecho Ormuz",
                        "url": DOMAIN + "/sobre.html",
                    }
                    value["publisher"] = {
                        "@type": "Organization",
                        "name": "Estrecho Ormuz",
                        "url": DOMAIN + "/",
                    }
                for k in list(value):
                    value[k] = walk(value[k])
            elif isinstance(value, list):
                value = [walk(v) for v in value]
            return value

        data = walk(data)
        return match.group(1) + json.dumps(data, ensure_ascii=False, separators=(",",":")) + match.group(3)

    return re.sub(
        r'(<script\b[^>]*type=["\']application/ld\+json["\'][^>]*>)(.*?)(</script>)',
        patch,
        document,
        flags=re.I | re.S,
    )

def add_signature(document: str, filename: str) -> str:
    if "PROFESSIONAL_EDITORIAL_SIGNATURE_V9" in document:
        return document
    if not re.search(r'"@type"\s*:\s*"(?:Article|NewsArticle|AnalysisNewsArticle|Report)"', document, re.I):
        return document
    lang = "en" if filename.startswith("en-") or filename == "en.html" else "es"
    block = (
        '<div class="editorial-signature-v9"><span>Publicación</span>'
        '<strong>Equipo editorial de Estrecho Ormuz</strong>'
        '<small>Fuentes contrastadas · Metodología pública · Política de correcciones</small></div>'
        if lang == "es" else
        '<div class="editorial-signature-v9"><span>Published by</span>'
        '<strong>Estrecho Ormuz Editorial Team</strong>'
        '<small>Cross-checked sources · Public methodology · Corrections policy</small></div>'
    )
    main = re.search(r"<main\b[^>]*>", document, re.I)
    if main:
        return document[:main.end()] + "\n<!-- PROFESSIONAL_EDITORIAL_SIGNATURE_V9 -->\n" + block + document[main.end():]
    return document

def sanitize_html(document: str, filename: str) -> str:
    document = prerender(document, filename)
    document = sanitize_text(document)
    document = editorialize_jsonld(document)
    document = add_signature(document, filename)
    document = re.sub(r'\s*<link\b[^>]*rel=["\']manifest["\'][^>]*>\s*', "\n", document, flags=re.I)
    if filename != "404.html" and "/public-ui.min.js" not in document:
        document = re.sub(
            r"</body>",
            '<script defer src="/public-ui.min.js"></script>\n</body>',
            document,
            count=1,
            flags=re.I,
        )
    if "/professional-v9.css" not in document:
        document = re.sub(
            r"</head>",
            '<link rel="stylesheet" href="/professional-v9.css">\n</head>',
            document,
            count=1,
            flags=re.I,
        )
    return document

