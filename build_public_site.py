def copy_asset(path: Path) -> bool:
    if path.name in BLOCKED_NAMES or path.suffix.lower() in BLOCKED_EXTENSIONS:
        return False
    if path.name in BLOCKED_DYNAMIC_JS or path.name.startswith("."):
        return False
    if path.name.startswith(("test_","install_","prepare_","build_","professionalize_")):
        return False
    return path.suffix.lower() in {
        ".css",".js",".png",".jpg",".jpeg",".webp",".svg",".ico",".xml",".txt"
    }

def write_sitemap():
    urls = []
    for path in sorted(OUT.rglob("*.html")):
        rel = path.relative_to(OUT).as_posix()
        if rel == "404.html" or rel in BLOCKED_HTML:
            continue
        body = path.read_text(encoding="utf-8")
        if re.search(r'<meta\b[^>]*name=["\']robots["\'][^>]*noindex', body, re.I):
            continue
        urls.append(DOMAIN + ("/" if rel == "index.html" else "/" + rel))
    today = datetime.now(timezone.utc).date().isoformat()
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for url in urls:
        lines.append(f"  <url><loc>{html.escape(url)}</loc><lastmod>{today}</lastmod></url>")
    lines.append("</urlset>")
    (OUT/"sitemap.xml").write_text("\n".join(lines)+"\n", encoding="utf-8")

def audit():
    errors = []
    for path in OUT.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(OUT).as_posix()
        if path.suffix.lower() in BLOCKED_EXTENSIONS:
            errors.append(f"blocked extension leaked: {rel}")
        if path.name in BLOCKED_NAMES:
            errors.append(f"blocked file leaked: {rel}")
        if path.suffix.lower() in {".html",".js",".css",".xml",".txt"}:
            body = path.read_text(encoding="utf-8", errors="ignore")
            for token in (
                "raw.githubusercontent.com/ElPtoWalter",
                "github.com/ElPtoWalter/estado-del-estrecho-de-Ormuz",
                'href="/status.json"',
                'href="/history.json"',
                "GITHUB_TOKEN",
                "CLOUDFLARE_API_TOKEN",
            ):
                if token in body:
                    errors.append(f"{rel}: forbidden token {token}")
    if errors:
        print("PUBLIC BUILD AUDIT FAILED", file=sys.stderr)
        for error in errors:
            print(" -", error, file=sys.stderr)
        raise SystemExit(2)

def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    for path in sorted(ROOT.rglob("*.html")):
        if OUT in path.parents or ".git" in path.parts or ".github" in path.parts:
            continue
        rel = path.relative_to(ROOT)
        if rel.as_posix() in BLOCKED_HTML:
            continue
        target = OUT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(sanitize_html(path.read_text(encoding="utf-8"), path.name), encoding="utf-8")

    for path in sorted(ROOT.iterdir()):
        if not path.is_file() or not copy_asset(path):
            continue
        if path.name in {"sitemap.xml","robots.txt"}:
            continue
        shutil.copy2(path, OUT/path.name)

    for dirname in ("diario","diary","briefs","images","assets"):
        source_dir = ROOT/dirname
        if not source_dir.exists():
            continue
        for path in source_dir.rglob("*"):
            if not path.is_file():
                continue
            rel = path.relative_to(ROOT)
            target = OUT/rel
            if path.suffix.lower() == ".html":
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(sanitize_html(path.read_text(encoding="utf-8"), path.name), encoding="utf-8")
            elif copy_asset(path):
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, target)

    (OUT/"public-ui.min.js").write_text(PUBLIC_UI, encoding="utf-8")
    (OUT/"professional-v9.css").write_text(PUBLIC_CSS.strip()+"\n", encoding="utf-8")
    (OUT/"_headers").write_text(HEADERS.strip()+"\n", encoding="utf-8")
    (OUT/"_redirects").write_text(REDIRECTS.strip()+"\n", encoding="utf-8")
    (OUT/"robots.txt").write_text(
        "User-agent: *\nAllow: /\n\nSitemap: https://estrechoormuz.com/sitemap.xml\n",
        encoding="utf-8",
    )
    write_sitemap()
    audit()
    print("Professional Security V9 public build created successfully.")
    print("No Python, JSON, workflows, configuration or internal engine files were published.")
    return 0

