def clean_jsonld(document: str, lang: str) -> str:
    def patch(match):
        try:
            data = json.loads(match.group(2))
        except json.JSONDecodeError:
            raw = PRIVATE_ENDPOINT_URL_RE.sub(
                DOMAIN + ("/metodologia.html" if lang == "es" else "/en-methodology.html"),
                match.group(2),
            )
            raw = PRIVATE_ENDPOINT_RE.sub(
                "datos internos del observatorio" if lang == "es" else "internal observatory data",
                raw,
            )
            return match.group(1) + raw + match.group(3)

        def walk(value):
            if isinstance(value, dict):
                if value.get("@type") == "DataDownload":
                    url = str(value.get("contentUrl") or value.get("url") or "")
                    if PRIVATE_ENDPOINT_RE.search(url):
                        return None
                if value.get("@type") in {"Article", "NewsArticle", "AnalysisNewsArticle", "Report"}:
                    value["author"] = {
                        "@type": "Organization",
                        "name": "Estrecho Ormuz",
                        "url": DOMAIN + ("/sobre.html" if lang == "es" else "/en-about.html"),
                    }
                    value["publisher"] = {"@type": "Organization", "name": "Estrecho Ormuz", "url": DOMAIN + "/"}
                main = value.get("mainEntity")
                if isinstance(main, dict):
                    main_url = str(main.get("url") or main.get("contentUrl") or "")
                    if PRIVATE_ENDPOINT_RE.search(main_url):
                        value.pop("mainEntity", None)
                for key in list(value):
                    child = value[key]
                    if key in {"url", "contentUrl"} and isinstance(child, str) and PRIVATE_ENDPOINT_RE.search(child):
                        if key == "contentUrl":
                            value.pop(key, None)
                        else:
                            value[key] = DOMAIN + ("/metodologia.html" if lang == "es" else "/en-methodology.html")
                    else:
                        patched = walk(child)
                        if patched is None and key == "distribution":
                            value.pop(key, None)
                        else:
                            value[key] = patched
            elif isinstance(value, list):
                value = [x for x in (walk(item) for item in value) if x is not None]
            elif isinstance(value, str):
                value = PRIVATE_ENDPOINT_URL_RE.sub(
                    DOMAIN + ("/metodologia.html" if lang == "es" else "/en-methodology.html"), value
                )
                value = PRIVATE_ENDPOINT_RE.sub(
                    "datos internos del observatorio" if lang == "es" else "internal observatory data", value
                )
                for old, new in PRO_LANGUAGE:
                    value = value.replace(old, new)
                value = value.replace("Informe generado automáticamente", "Informe editorial elaborado")
                value = value.replace("Report generated automatically", "Editorial report prepared")
            return value

        data = walk(data)
        return match.group(1) + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + match.group(3)

    return re.sub(
        r'(<script\b[^>]*type=["\']application/ld\+json["\'][^>]*>)(.*?)(</script>)',
        patch, document, flags=re.I | re.S,
    )

