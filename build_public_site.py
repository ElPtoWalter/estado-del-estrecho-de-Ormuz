def private_name(path: Path) -> bool:
    name = path.name
    if path.suffix.lower() in PRIVATE_EXTENSIONS:
        return True
    if any(name.upper().startswith(prefix.upper()) for prefix in PRIVATE_PREFIXES):
        return True
    return name in {"CNAME", "llms.txt", "humans.txt"}

def javascript_is_private(path: Path) -> bool:
    if path.suffix.lower() != ".js":
        return False
    if path.name in {
        "app.js", "daily-brief.js", "evidence-ui.js", "evidence-archive.js",
        "operational-v7.js", "widget.js", "social-studio.js",
    }:
        return True
    try:
        body = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return True
    return bool(PRIVATE_ENDPOINT_RE.search(body))

def copy_asset(path: Path) -> bool:
    if path.name == "monitor-records.csv":
        return True
    if private_name(path) or path.name.startswith("."):
        return False
    suffix = path.suffix.lower()
    if suffix == ".txt":
        return path.name == "ads.txt"
    if suffix == ".js" and javascript_is_private(path):
        return False
    return suffix in {".css", ".js", ".png", ".jpg", ".jpeg", ".webp", ".svg", ".ico", ".xml"}

def write_sitemap() -> None:
    urls = []
    for path in sorted(OUT.rglob("*.html")):
        rel = path.relative_to(OUT).as_posix()
        if rel == "404.html" or rel in BLOCKED_HTML:
            continue
        body = path.read_text(encoding="utf-8")
        if re.search(r'<meta\b[^>]*name=["\']robots["\'][^>]*noindex', body, re.I):
            continue
        urls.append(DOMAIN + ("/" if rel == "index.html" else "/" + rel))
    today = datetime.now(timezone.utc).date().isoformat()
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for url in urls:
        lines.append(f"  <url><loc>{html.escape(url)}</loc><lastmod>{today}</lastmod></url>")
    lines.append("</urlset>")
    (OUT / "sitemap.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")

def audit_public_build() -> None:
    errors = []
    forbidden_tokens = (
        "status.json", "history.json", "config.json", "operational-intelligence.json",
        "journal-state.json", "journal-health.json", "raw.githubusercontent.com/ElPtoWalter",
        "github.com/ElPtoWalter/estado-del-estrecho-de-Ormuz",
        "Redacción automatizada", "Automated newsroom",
        "El texto se genera automáticamente", "The text is generated automatically",
        "Puntuación de novedad", "Novelty score",
        "Crónica diaria automática", "Daily automated",
        "API pública", "Public API", "JSON API", "API JSON",
        "social-studio.html", "ChatGPT", "OpenAI",
    )

    for path in OUT.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(OUT).as_posix()
        if private_name(path):
            errors.append(f"private file leaked: {rel}")
            continue
        if path.suffix.lower() == ".js" and javascript_is_private(path):
            errors.append(f"private javascript leaked: {rel}")
            continue
        if path.suffix.lower() in {".html", ".js", ".css", ".xml", ".txt"}:
            body = path.read_text(encoding="utf-8", errors="ignore")
            for token in forbidden_tokens:
                if token.lower() in body.lower():
                    errors.append(f"{rel}: forbidden public token {token!r}")

    for required in ("index.html", "en.html", "robots.txt", "sitemap.xml"):
        if not (OUT / required).exists():
            errors.append(f"missing required public file: {required}")

    for forbidden in (
        "status.json", "history.json", "config.json", "update_status.py",
        "operational-intelligence.json", "social-studio.js", "widget.js", "_redirects",
    ):
        if (OUT / forbidden).exists():
            errors.append(f"forbidden public file exists: {forbidden}")

    if errors:
        print("PUBLIC BUILD AUDIT FAILED", file=sys.stderr)
        for error in errors:
            print(" -", error, file=sys.stderr)
        raise SystemExit(2)

def main() -> int:
    build_reports(ROOT)
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    for path in sorted(ROOT.rglob("*.html")):
        if OUT in path.parents or ".git" in path.parts or ".github" in path.parts:
            continue
        rel = path.relative_to(ROOT)
        if rel.as_posix() in BLOCKED_HTML or path.name in BLOCKED_HTML:
            continue
        target = OUT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            apply_policy(sanitize_html(path.read_text(encoding="utf-8"), path.name), rel.as_posix()),
            encoding="utf-8",
        )

    for path in sorted(ROOT.iterdir()):
        if not path.is_file() or not copy_asset(path):
            continue
        if path.name in {"sitemap.xml", "robots.txt"}:
            continue
        shutil.copy2(path, OUT / path.name)

    for dirname in ("diario", "diary", "briefs", "images", "assets"):
        source_dir = ROOT / dirname
        if not source_dir.exists():
            continue
        for path in source_dir.rglob("*"):
            if not path.is_file():
                continue
            rel = path.relative_to(ROOT)
            target = OUT / rel
            if path.suffix.lower() == ".html":
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(
                    apply_policy(sanitize_html(path.read_text(encoding="utf-8"), path.name), rel.as_posix()),
                    encoding="utf-8",
                )
            elif copy_asset(path):
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, target)

    (OUT / "public-ui.min.js").write_text((ROOT / "public-ui.js").read_text(encoding="utf-8"), encoding="utf-8")
